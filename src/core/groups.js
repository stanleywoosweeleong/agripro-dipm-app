// Pest GROUPS — the unit of decision-making.
//
// Instead of cataloguing every species in the world, every pest is placed
// into a group defined by traits that decide control:
//   • what it is (taxon)           → which chemistries can work at all
//   • how it feeds (mouthparts)    → contact / stomach / systemic
//   • where it hides               → can a spray even reach it?
//   • which life stage does damage → growth regulators vs. adulticides
//
// A pest that is not in any database still lands in one of these groups
// through the diagnosis questions, and gets sound advice.
//
// chem[].fit: 'best' | 'good' | 'limited'
// avoid[]:    MoA codes that DON'T work or make things worse, with the reason.

